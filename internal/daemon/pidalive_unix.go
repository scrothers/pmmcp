//go:build unix

package daemon

import (
	"errors"
	"syscall"
)

// pidAlive reports whether an OS process with pid is currently alive. Signal 0
// performs error checking without delivering a signal: nil means alive; EPERM
// means alive but owned by another user (still counts as alive).
func pidAlive(pid int) bool {
	if pid <= 0 {
		return false
	}
	err := syscall.Kill(pid, 0)
	if err == nil {
		return true
	}
	return errors.Is(err, syscall.EPERM)
}
